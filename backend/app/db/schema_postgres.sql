CREATE TABLE IF NOT EXISTS public.holidays (
    holiday_date DATE PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL REFERENCES public.employees(employee_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    work_date DATE NOT NULL,
    -- Stored in local company time (Asia/Ho_Chi_Minh) to align with work_date + policy work_start.
    check_in TIMESTAMP WITHOUT TIME ZONE,
    check_out TIMESTAMP WITHOUT TIME ZONE,
    status TEXT NOT NULL DEFAULT 'present'
        CHECK (status IN ('present', 'absent', 'on_leave', 'holiday', 'weekend')),
    source TEXT NOT NULL DEFAULT 'biometric',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (employee_id, work_date),
    -- Allow missing check_in OR missing check_out (required for R2 missing_punch & kiosk edge cases).
    CHECK (check_out IS NULL OR check_in IS NULL OR check_out >= check_in)
);

CREATE TABLE IF NOT EXISTS public.leave_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL REFERENCES public.employees(employee_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    leave_type TEXT NOT NULL CHECK (leave_type IN ('annual', 'sick', 'personal', 'unpaid')),
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    requires_executive_approval SMALLINT NOT NULL DEFAULT 0
        CHECK (requires_executive_approval IN (0, 1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_by TEXT REFERENCES public.employees(employee_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    decision_note TEXT,
    cancelled_at TIMESTAMPTZ,
    CHECK (to_date >= from_date)
);

CREATE TABLE IF NOT EXISTS public.leave_approval_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES public.leave_requests(request_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    actor_user_id TEXT NOT NULL REFERENCES public.users(user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    action TEXT NOT NULL CHECK (action IN ('submit', 'approve', 'reject', 'cancel', 'override')),
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.overtime_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL REFERENCES public.employees(employee_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    work_date DATE NOT NULL,
    start_time TIME,
    end_time TIME,
    reason TEXT,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    approved_by TEXT REFERENCES public.employees(employee_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ,
    UNIQUE (employee_id, work_date),
    CHECK (start_time IS NULL OR end_time IS NULL OR end_time > start_time)
);

