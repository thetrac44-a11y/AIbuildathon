CREATE TABLE IF NOT EXISTS public.departments (
    department_id TEXT PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.positions (
    position_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.employees (
    employee_id TEXT PRIMARY KEY,
    full_name TEXT NOT NULL,
    department_id TEXT NOT NULL REFERENCES public.departments(department_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- Keep position as text for compatibility with current source code.
    -- position_id is the normalized link for master-data dropdowns.
    position TEXT NOT NULL,
    position_id BIGINT REFERENCES public.positions(position_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    manager_id TEXT REFERENCES public.employees(employee_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    start_date DATE NOT NULL,
    annual_leave_balance NUMERIC(7,2) NOT NULL DEFAULT 12.00
        CHECK (annual_leave_balance >= 0),
    -- Aligned across employees, roles, and query_audit_log (5 enterprise roles).
    role TEXT NOT NULL DEFAULT 'employee'
        CHECK (role IN ('employee', 'manager', 'hr', 'admin', 'executive')),
    employment_status TEXT NOT NULL DEFAULT 'active'
        CHECK (employment_status IN ('active', 'inactive', 'terminated')),
    email TEXT UNIQUE,
    phone TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (manager_id IS NULL OR manager_id <> employee_id)
);

