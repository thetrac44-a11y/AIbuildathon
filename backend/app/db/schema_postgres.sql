CREATE TABLE IF NOT EXISTS public.attendance_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_name TEXT NOT NULL,
    department_id TEXT REFERENCES public.departments(department_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    timezone_name TEXT NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    work_start TIME NOT NULL DEFAULT TIME '08:30',
    work_end TIME NOT NULL DEFAULT TIME '17:30',
    break_minutes INTEGER NOT NULL DEFAULT 60 CHECK (break_minutes >= 0),
    grace_late_minutes INTEGER NOT NULL DEFAULT 5 CHECK (grace_late_minutes >= 0),
    target_work_hours NUMERIC(5,2) NOT NULL DEFAULT 8.00 CHECK (target_work_hours > 0),
    effective_from DATE NOT NULL DEFAULT DATE '2026-01-01',
    effective_to DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by_user_id TEXT REFERENCES public.users(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CHECK (work_end <> work_start)
);

-- Guarantee at most 1 active global policy and 1 active policy per department.
CREATE UNIQUE INDEX IF NOT EXISTS idx_attendance_policies_one_global_active
    ON public.attendance_policies ((1))
    WHERE department_id IS NULL AND is_active = TRUE;

CREATE UNIQUE INDEX IF NOT EXISTS idx_attendance_policies_one_dept_active
    ON public.attendance_policies (department_id)
    WHERE department_id IS NOT NULL AND is_active = TRUE;

