CREATE TABLE IF NOT EXISTS public.anomalies (
    anomaly_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT REFERENCES public.employees(employee_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    department_id TEXT REFERENCES public.departments(department_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    scope_type TEXT NOT NULL DEFAULT 'employee'
        CHECK (scope_type IN ('employee', 'department')),
    rule_code TEXT NOT NULL CHECK (rule_code IN ('R1','R2','R3','R4','R5','R6','R7','R8')),
    anomaly_type TEXT NOT NULL CHECK (anomaly_type IN (
        'late_repeated', 'missing_punch', 'low_hours', 'leave_near_holiday',
        'leave_cluster', 'identical_punch', 'weekend_punch', 'leave_over_balance'
    )),
    severity TEXT NOT NULL CHECK (severity IN ('low', 'medium', 'high')),
    period TEXT NOT NULL CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
    explanation TEXT NOT NULL,
    review_status TEXT NOT NULL DEFAULT 'open'
        CHECK (review_status IN ('open', 'confirmed', 'dismissed')),
    reviewed_by TEXT REFERENCES public.employees(employee_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    review_note TEXT,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    dedup_key TEXT NOT NULL UNIQUE,
    CHECK ((scope_type = 'employee' AND employee_id IS NOT NULL)
        OR (scope_type = 'department' AND department_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.query_audit_log (
