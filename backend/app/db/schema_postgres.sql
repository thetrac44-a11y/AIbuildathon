CREATE OR REPLACE VIEW public.v_attendance_daily AS
SELECT
    a.id,
    a.employee_id,
    e.full_name,
    e.department_id,
    d.name AS department_name,
    a.work_date,
    TO_CHAR(a.work_date, 'YYYY-MM') AS period,
    a.check_in,
    a.check_out,
    a.status,
    a.source,
    CASE
        WHEN a.status = 'present'
         AND a.check_in IS NOT NULL
         AND (EXTRACT(EPOCH FROM (a.check_in - (a.work_date::timestamp + COALESCE(pol.work_start, TIME '08:30'))))::numeric / 60.0)
             > COALESCE(pol.grace_late_minutes, 5)
        THEN ROUND(
            EXTRACT(EPOCH FROM (a.check_in - (a.work_date::timestamp + COALESCE(pol.work_start, TIME '08:30'))))::numeric / 60.0
        )::INTEGER
        ELSE 0
    END AS late_minutes,
    CASE
        WHEN a.status = 'present'
         AND a.check_in IS NOT NULL
         AND (EXTRACT(EPOCH FROM (a.check_in - (a.work_date::timestamp + COALESCE(pol.work_start, TIME '08:30'))))::numeric / 60.0)
             > COALESCE(pol.grace_late_minutes, 5)
        THEN 1 ELSE 0
    END AS is_late,
    CASE
        WHEN a.status = 'present' AND a.check_in IS NOT NULL AND a.check_out IS NOT NULL
        THEN ROUND(GREATEST(
            0.0::numeric,
            (EXTRACT(EPOCH FROM (a.check_out - a.check_in))::numeric / 3600.0)
            - CASE
                WHEN (EXTRACT(EPOCH FROM (a.check_out - a.check_in))::numeric / 3600.0) > 5.0
                THEN (COALESCE(pol.break_minutes, 60)::numeric / 60.0)
                ELSE 0.0::numeric
              END
        ), 2)
        ELSE 0.0::numeric
    END AS work_hours,
    CASE WHEN EXTRACT(ISODOW FROM a.work_date) IN (6, 7) THEN 1 ELSE 0 END AS is_weekend,
    CASE WHEN h.holiday_date IS NOT NULL THEN 1 ELSE 0 END AS is_holiday
FROM public.attendance a
JOIN public.employees e ON e.employee_id = a.employee_id
JOIN public.departments d ON d.department_id = e.department_id
LEFT JOIN public.holidays h ON h.holiday_date = a.work_date
LEFT JOIN LATERAL (
    SELECT
        ap.work_start,
        ap.grace_late_minutes,
        ap.break_minutes
    FROM public.attendance_policies ap
    WHERE ap.is_active = TRUE
      AND (ap.department_id = e.department_id OR ap.department_id IS NULL)
      AND ap.effective_from <= a.work_date
      AND (ap.effective_to IS NULL OR ap.effective_to >= a.work_date)
    ORDER BY (ap.department_id IS NOT NULL) DESC, ap.effective_from DESC, ap.policy_id DESC
    LIMIT 1
) pol ON TRUE;

